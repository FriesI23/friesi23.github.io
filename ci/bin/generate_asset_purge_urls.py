"""Generate ci/asset_purge_urls.txt from the Jekyll _site/assets directory.

Run via:  make gen-asset-purge-urls  (requires a prior jekyll build)
"""

import argparse
from pathlib import Path

SITE_URL = "https://friesi23.icu"

# Subtrees that are never directly loaded by browsers
_EXCLUDE_PREFIXES = (
    "js/plugins/",   # bundled into main.min.js by jekyll build
    "prompts/",      # content files; not matched by nginx static-asset location
)

# Individual files not served in production
_EXCLUDE_FILES = {
    "js/_main.js",          # concatenation source, not referenced in HTML
    "js/lunr/lunr.js",      # non-minified copy; production uses lunr.min.js
    "js/lunr/lunr-gr.js",   # Greek language pack, not loaded
}

_EXCLUDE_EXTENSIONS = {".map"}


def _should_include(rel: str) -> bool:
    if any(rel.startswith(p) for p in _EXCLUDE_PREFIXES):
        return False
    if rel in _EXCLUDE_FILES:
        return False
    if Path(rel).suffix in _EXCLUDE_EXTENSIONS:
        return False
    return True


def collect_urls(site_assets: Path, site_url: str) -> list[str]:
    by_group: dict[str, list[str]] = {}
    for f in sorted(site_assets.rglob("*")):
        if not f.is_file():
            continue
        rel = f.relative_to(site_assets).as_posix()
        if not _should_include(rel):
            continue
        group = rel.split("/")[0]
        by_group.setdefault(group, []).append(f"{site_url}/assets/{rel}")

    lines: list[str] = []
    for group in sorted(by_group):
        lines.append(f"# {group}")
        lines.extend(by_group[group])
    return lines


def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description=(
            "Scan _site/assets and write a purge URL list to ci/asset_purge_urls.txt. "
            "Requires a prior 'bundle exec jekyll build' (or 'make serve PROD=1')."
        )
    )
    p.add_argument(
        "--site-dir",
        default="_site",
        help="Path to Jekyll build output directory (default: _site)",
    )
    p.add_argument(
        "--site-url",
        default=SITE_URL,
        help=f"Absolute site base URL, no trailing slash (default: {SITE_URL})",
    )
    p.add_argument(
        "--output",
        metavar="FILE",
        default=None,
        help="Write to FILE instead of stdout",
    )
    return p


if __name__ == "__main__":
    args = _build_parser().parse_args()

    site_assets = Path(args.site_dir) / "assets"
    if not site_assets.is_dir():
        raise SystemExit(
            f"error: {site_assets} not found — run 'bundle exec jekyll build' first"
        )

    urls = collect_urls(site_assets, args.site_url)
    header = (
        "# static assets purged on full-mode manual purge\n"
        "# generated by: make gen-asset-purge-urls\n"
    )
    content = header + "\n".join(urls) + "\n"

    if args.output:
        Path(args.output).write_text(content)
        print(f"[gen] wrote {len(urls)} asset URL(s) to {args.output}")
    else:
        print(content, end="")
